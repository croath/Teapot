impl Locale {
  pub fn t(self, msg: Msg) -> &'static str {
    match self {
      Locale::En => msg.en(),
      Locale::Ja => msg.ja(),
      Locale::ZhHans => msg.zh_hans(),
      Locale::ZhHant => msg.zh_hant(),
      Locale::Ko => msg.ko(),
    }
  }
}

